#!/usr/bin/env node
/*
 * Regenerate lib/ofac-full.ts from the sanctions-api wallet snapshot.
 *
 * The feed (alazk/sanctions-api → wallets.json) is an OpenSanctions export of
 * every crypto wallet on a sanctions list, all regimes. Each entry looks like:
 *
 *   { "id": "...-wallet-eth-0x..", "caption": "0xABC…", "datasets": ["us_ofac_sdn", …], "topics": [...] }
 *
 * The caption is the address in checksum case. Many are EVM addresses tagged
 * eth/bsc/etc — all the same 0x + 40 hex shape and all valid on Ethereum, so
 * every caption matching that shape is an address the denylist must screen.
 * BTC / TRON / other-format wallets never match the pattern and drop out on
 * their own. We lower-case, de-duplicate (first-seen order), and emit the array
 * the policy loads on-chain via setparams.mjs.
 *
 * Paths:
 *   input  — $WALLETS_JSON, else ../../sanctions-api/wallets.json relative to
 *            this file. That default is the CI layout: policy-builder/ and
 *            sanctions-api/ are sibling checkouts, this script sits in
 *            policy-builder/scripts/, so ../../sanctions-api is the sibling.
 *   output — ../lib/ofac-full.ts (always, so the app imports a stable path).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const IN = process.env.WALLETS_JSON || resolve(HERE, "../../sanctions-api/wallets.json");
const OUT = resolve(HERE, "../lib/ofac-full.ts");

const ETH = /^0x[0-9a-fA-F]{40}$/;

let feed;
try {
  feed = JSON.parse(readFileSync(IN, "utf8"));
} catch (e) {
  console.error(`Could not read the wallet snapshot at ${IN}`);
  console.error("Set WALLETS_JSON, or check out alazk/sanctions-api beside this repo.");
  console.error(String(e?.message ?? e));
  process.exit(1);
}

const wallets = Array.isArray(feed) ? feed : (feed.wallets ?? []);
if (!wallets.length) {
  console.error("The snapshot parsed but held no wallets — refusing to emit an empty list.");
  process.exit(1);
}

// The address may live in `caption` (checksum case), be embedded in `id`
// (e.g. "fr-ga-wallet-eth-0x…"), or — for other snapshot shapes — sit in an
// `address`/`wallet` field or be the entry itself if it's a bare string. Try
// the clean fields first, then fall back to scanning the whole entry for an
// 0x + 40-hex run. Lower-cased and de-duplicated in first-seen order; a wallet
// sanctioned by two regimes is still one entry on-chain.
const ANY_ETH = /0x[0-9a-fA-F]{40}/;
const seen = new Set();
const addresses = [];
const regimeTally = new Map(); // dataset slug → count, for the human summary only

function pick(w) {
  if (typeof w === "string") return ETH.test(w.trim()) ? w.trim() : null;
  for (const field of [w?.caption, w?.address, w?.wallet, w?.id]) {
    if (typeof field !== "string") continue;
    const s = field.trim();
    if (ETH.test(s)) return s; // whole field is the address
    const m = s.match(ANY_ETH); // address embedded in a slug like the id
    if (m) return m[0];
  }
  const m = JSON.stringify(w).match(ANY_ETH); // last resort: anywhere in the entry
  return m ? m[0] : null;
}

for (const w of wallets) {
  const hit = pick(w);
  if (!hit) continue;
  const addr = hit.toLowerCase();
  if (seen.has(addr)) continue;
  seen.add(addr);
  addresses.push(addr);
  for (const d of w?.datasets ?? []) regimeTally.set(d, (regimeTally.get(d) ?? 0) + 1);
}

if (!addresses.length) {
  console.error("No Ethereum-format addresses found in the snapshot — refusing to emit an empty list.");
  // Diagnostics: show what we actually read so the shape is visible in the log.
  console.error(`  read from : ${IN}`);
  console.error(`  top-level : ${Array.isArray(feed) ? "array" : "object { " + Object.keys(feed).join(", ") + " }"}`);
  console.error(`  wallets   : ${wallets.length} entries`);
  console.error(`  first     : ${JSON.stringify(wallets[0])?.slice(0, 300)}`);
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const body = addresses.map((a) => `  "${a}",`).join("\n");
const out = `// GENERATED by \`node scripts/emit-full-list.mjs\`. Do not edit.
//
// Every sanctioned Ethereum address in the live OpenSanctions snapshot at
// generation time — all regimes, not OFAC alone. This is the enforcement set
// the denylist policy screens against, loaded on-chain via setparams.mjs.
//
// ${addresses.length} addresses · generated ${today}

export const OFAC_FULL: string[] = [
${body}
];
`;

writeFileSync(OUT, out);

// Summary to stdout — the CI log, or the terminal. Not part of the artifact.
console.log(`Wrote ${addresses.length} addresses to ${OUT}`);
const breakdown = [...regimeTally.entries()].sort((a, b) => b[1] - a[1]);
if (breakdown.length) {
  console.log("By dataset:");
  for (const [slug, n] of breakdown) console.log(`  ${String(n).padStart(4)}  ${slug}`);
}
